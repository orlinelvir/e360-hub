import { NextResponse } from "next/server";
import type { QueryDocumentSnapshot } from "firebase-admin/firestore";
import { adminDb } from "@/lib/firebase-admin";

// "Duración de 6 a 12 meses" según data/services.ts — pasado ese punto se asume
// que el caso se revisa manualmente en vez de seguir generando rondas solas.
const ROUND_INTERVAL_DAYS = 30;
const MAX_AUTO_ROUNDS = 12;
const FEE_AMOUNT = 10;
const PAYMENT_LINK = "https://link.fastpaydirect.com/payment-link/6a8688d6f9c8c807930b9166";

/**
 * Cron diario (ver vercel.json) que avanza la ronda de seguimiento mensual de
 * cada caso activo de Reparación de Crédito. Por cada cliente cuya última ronda
 * tenga 30+ días, crea la siguiente ronda (pending_review) y notifica al broker
 * que debe pagar el fee de $10 correspondiente a E360.
 *
 * Autenticado con el mismo secreto que Vercel Cron inyecta automáticamente
 * cuando existe la env var CRON_SECRET (ver https://vercel.com/docs/cron-jobs).
 */
export async function GET(request: Request) {
  const auth = request.headers.get("authorization");
  if (!process.env.CRON_SECRET || auth !== `Bearer ${process.env.CRON_SECRET}`) {
    return NextResponse.json({ error: "No autorizado" }, { status: 401 });
  }

  if (!adminDb) {
    return NextResponse.json({ error: "Servidor no configurado" }, { status: 500 });
  }

  try {
    const snap = await adminDb.collectionGroup("feeRounds").get();

    // Agrupar por leadId: cada cliente de Reparación de Crédito tiene su propia serie de rondas.
    const byLead = new Map<string, QueryDocumentSnapshot[]>();
    for (const roundDoc of snap.docs) {
      const leadId = roundDoc.data().leadId as string | undefined;
      if (!leadId) continue;
      if (!byLead.has(leadId)) byLead.set(leadId, []);
      byLead.get(leadId)!.push(roundDoc);
    }

    const now = Date.now();
    const created: { leadId: string; roundNumber: number }[] = [];

    for (const [leadId, docs] of byLead) {
      docs.sort((a, b) => (Number(b.data().roundNumber) || 0) - (Number(a.data().roundNumber) || 0));
      const latest = docs[0];
      const latestData = latest.data();
      const roundNumber = Number(latestData.roundNumber) || 1;

      if (roundNumber >= MAX_AUTO_ROUNDS) continue;

      const createdAtMs = new Date(latestData.createdAt).getTime();
      if (Number.isNaN(createdAtMs)) continue;

      const daysSince = (now - createdAtMs) / (1000 * 60 * 60 * 24);
      if (daysSince < ROUND_INTERVAL_DAYS) continue;

      // Evita duplicar si el cron ya corrió y creó la siguiente ronda.
      const alreadyHasNext = docs.some((d) => (Number(d.data().roundNumber) || 0) === roundNumber + 1);
      if (alreadyHasNext) continue;

      const clientRef = latest.ref.parent.parent;
      if (!clientRef) continue;

      const clientSnap = await clientRef.get();
      if (!clientSnap.exists) continue;
      const clientData = clientSnap.data() || {};
      const brokerId = (latestData.brokerId as string) || (clientData.brokerId as string);
      const clientEmail = (latestData.clientEmail as string) || (clientData.email as string) || "";
      const clientName = (clientData.name as string) || "Cliente";
      const nextRoundNumber = roundNumber + 1;

      const newRoundRef = await clientRef.collection("feeRounds").add({
        roundNumber: nextRoundNumber,
        amount: FEE_AMOUNT,
        status: "pending_review",
        paymentLink: PAYMENT_LINK,
        clientEmail,
        brokerId,
        leadId,
        autoGenerated: true,
        createdAt: new Date().toISOString()
      });

      await clientRef.update({
        feeRoundStatus: "pending_review",
        feeRoundNumber: nextRoundNumber,
        lastActivity: `Ronda ${nextRoundNumber} de seguimiento mensual generada automáticamente`
      });

      if (brokerId) {
        await adminDb.collection("notifications").add({
          recipientId: brokerId,
          type: "fee_round_due",
          message: `Reparación de Crédito · ${clientName}: ronda ${nextRoundNumber} lista. Recuerda pagar a E360 el fee de $${FEE_AMOUNT}.`,
          clientId: clientRef.id,
          leadId,
          roundId: newRoundRef.id,
          read: false,
          createdAt: new Date().toISOString()
        });
      }

      created.push({ leadId, roundNumber: nextRoundNumber });
    }

    return NextResponse.json({ checked: byLead.size, created: created.length, details: created });
  } catch (error) {
    console.error("Error en cron de rondas mensuales de Reparación de Crédito:", error);
    return NextResponse.json({ error: "Error al procesar rondas mensuales" }, { status: 500 });
  }
}
